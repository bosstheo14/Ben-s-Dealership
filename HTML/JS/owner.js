/* ==========================================================================
   owner.js — Owner tools.

   This page never touches the live website. It loads whatever is currently in
   data.js, lets the owner edit it in a friendly form, and then hands back a
   brand new data.js file to download. The maintainer drops that file into the
   project and pushes it. Nothing here needs a server, a login or a password,
   because nothing here can change what the public sees.
   ========================================================================== */
