function downloadText(filename, content, type){
  var blob = new Blob([content], {type: type || "text/plain"});
  var url = URL.createObjectURL(blob);
  var a = document.createElement("a");
  a.href = url; a.download = filename;
  document.body.appendChild(a); a.click(); a.remove();
  setTimeout(function(){ URL.revokeObjectURL(url); }, 1000);
}

/* ---------- photos ---------- */
function slug(s){
  return String(s || "photo").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
}
function resize(file, cb){
  if(!/^image\//.test(file.type)){ cb(null); return; }
  var reader = new FileReader();
  reader.onerror = function(){ NM.toast("That file could not be read."); cb(null); };
  reader.onload = function(){
    var img = new Image();
    img.onerror = function(){ NM.toast("That image could not be opened."); cb(null); };
    img.onload = function(){
      var max = 1400, w = img.width, h = img.height;
      if(w > max || h > max){ var r = Math.min(max/w, max/h); w = Math.round(w*r); h = Math.round(h*r); }
      var c = document.createElement("canvas");
      c.width = w; c.height = h;
      var ctx = c.getContext("2d");
      ctx.fillStyle = "#fff"; ctx.fillRect(0, 0, w, h);
      ctx.drawImage(img, 0, 0, w, h);
      c.toBlob(function(blob){ cb(blob); }, "image/jpeg", 0.72);
    };
    img.src = reader.result;
  };
  reader.readAsDataURL(file);
}
function addPhotos(files){
  var list = Array.prototype.slice.call(files);
  if(!list.length) return;
  var base = slug([editing.year, editing.make, editing.model].filter(Boolean).join("-") || editing.id || "vehicle");
  var startAt = (editing.photos || []).length;
  var done = 0;
  NM.toast("Resizing " + list.length + (list.length === 1 ? " photo\u2026" : " photos\u2026"));
  list.forEach(function(file, i){
    resize(file, function(blob){
      if(blob){
        var name = base + "-" + (startAt + i + 1) + ".jpg";
        editing.photos.push("assets/img/" + name);
        pending.push({name: name, blob: blob, url: URL.createObjectURL(blob)});
      }
      if(++done === list.length){ render(); NM.toast("Photos ready. Download them before you close this page."); }
    });
  });
}

